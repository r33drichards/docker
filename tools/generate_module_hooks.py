#!/usr/bin/env python3
"""Generate the complete Module hook adapters, inventory and TypeScript event map.
The inventory is reviewed input, not a claim that arbitrary SDK pointers are safe.
--upstream checks every On* signature and the actual Implementation event table.
"""

import argparse
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "bindings/module_hooks.json"


def validate(data):
    hooks = data["hooks"]
    for key in ("native", "js"):
        names = [h[key] for h in hooks]
        if len(set(names)) != len(names):
            raise ValueError(f"duplicate {key}")
    for h in hooks:
        if not re.fullmatch(r"On[A-Za-z0-9]+", h["native"]):
            raise ValueError("invalid native hook")
        expected = h["native"][2].lower() + h["native"][3:]
        if h["js"] != expected or h["result"] not in ("void", "ModResult"):
            raise ValueError("invalid hook mapping")
        if h["signature"] != ", ".join(a["type"] + " " + a["name"] for a in h["args"]):
            raise ValueError("signature/argument drift")
        if h["adapter"] not in ("command", "generated"):
            raise ValueError("unknown adapter")
        if h.get("mutation") != (h["js"] if h["js"] in MUTATIONS else None):
            raise ValueError("mutation adapter drift")
        if h["failure"] not in ("pass", "deny") or type(h["allow"]) is not bool:
            raise ValueError("invalid result policy")
    return hooks


def upstream_check(hooks, path):
    source = path.read_text()
    actual = {
        name: (result, " ".join(args.split()))
        for result, name, args in re.findall(
            r"virtual\s+(void|ModResult)\s+(On\w+)\(([^;]*?)\)(?:\s+ATTR_NOT_NULL\([^;]*?\))?;",
            source,
        )
    }
    expected = {h["native"]: (h["result"], h["signature"]) for h in hooks}
    if actual != expected:
        raise ValueError(
            f"upstream hook drift: missing={actual.keys() - expected.keys()}, "
            f"stale={expected.keys() - actual.keys()}, "
            f"changed={[n for n in actual.keys() & expected.keys() if actual[n] != expected[n]]}"
        )
    table = set(re.findall(r"\bI_(On\w+)\b", source.split("class CoreExport Module", 1)[0]))
    if table != set(expected) - {"OnCleanup"}:
        raise ValueError("Implementation table does not match hook inventory")


MUTATIONS = {
    "userPreMessage": ("HookMessageMutation", "details"),
    "userPart": ("HookPartMutation", "partmessage, except_list"),
    "buildNeighborList": ("HookNeighborMutation", "include, exceptions"),
    "userPreJoin": ("HookJoinMutation", "privs"),
    "preChangeConnectClass": ("HookConnectMutation", "errnum"),
}


def outputs(hooks):
    notice = "// Generated by tools/generate_module_hooks.py; do not edit.\n"
    specs = (
        notice
        + "#pragma once\nstruct HookSpec { const char* name; bool decision; bool allow; bool failclosed; };\n"
    )
    specs += "inline constexpr HookSpec HookSpecs[] = {\n"
    adapters = notice
    types = notice + "interface ModuleHookEvents {\n"
    coverage = "# Module hook coverage (InspIRCd 4.12.1)\n\n"
    coverage += "All 74 Implementation events plus the direct OnCleanup callback. Native references are owned read-only snapshots; only command rewrites, five bounded explicit patch adapters, and explicit queued effects mutate native state.\n\n"
    coverage += "| Native hook | JS stage | Result | Callback failure |\n|---|---|---|---|\n"
    for h in hooks:
        decision = h["result"] == "ModResult"
        specs += '\t{{"{}", {}, {}, {}}},\n'.format(
            h["js"],
            str(decision).lower(),
            str(h["allow"]).lower(),
            str(h["failure"] == "deny").lower(),
        )
        coverage += f"| {h['native']} | \x60{h['js']}\x60 | {'pass/deny' + ('/allow (admin)' if h['allow'] else '') if decision else 'observe'} | {h['failure'] if decision else 'observe only'} |\n"
        if h["adapter"] == "command":
            continue
        types += (
            f"  {h['js']}: {{" + "; ".join(a["name"] + ": " + a["ts"] for a in h["args"]) + "};\n"
        )
        call = 'DispatchHook("{}", {}, [&](HookSnapshot& snapshot, v8::Local<v8::Object> event) {{\n'.format(
            h["js"], h["actor"]
        )
        call += (
            "\t\t\treturn "
            + (
                " &&\n\t\t\t\t".join(
                    f'snapshot.Field(event, "{a["name"]}", {a["name"]})' for a in h["args"]
                )
                or "snapshot.Ok()"
            )
            + ";\n\t\t})"
        )
        adapters += f"\t{h['result']} {h['native']}({h['signature']}) override\n\t{{\n\t\t"
        if h["js"] in MUTATIONS:
            cls, args = MUTATIONS[h["js"]]
            adapters += f"{cls} mutation({args});\n\t\t"
            call = (
                call[:-1]
                + ", [&](v8::Local<v8::Context> context, v8::Local<v8::Value> patch, Authority authority, std::vector<std::function<void()>>& commits) {\n\t\t\treturn mutation.Apply(context, patch, authority, commits);\n\t\t})"
            )
        adapters += ("return " if decision else "") + call + ";\n\t}\n"
    types += "}\ninterface ModuleHookPatches {\n"
    types += "  userPreMessage: {text?: string; exemptions?: string[]; tagsOut?: {name: string; value: string}[]; echo?: boolean; echoOriginal?: boolean; updateIdle?: boolean};\n"
    types += "  userPart: {partmessage?: string; exemptions?: string[]};\n"
    types += "  buildNeighborList: {includeChannels?: string[]; exceptions?: {userId: string; include: boolean}[]};\n"
    types += "  userPreJoin: {privs?: string};\n"
    types += "  preChangeConnectClass: {errnum?: {code: number; params: string[]} | null};\n"
    probe = notice
    for h in hooks:
        args = []
        for arg in h["args"]:
            name = arg["name"]
            type_name = arg["type"].removeprefix("const ").removesuffix("&").strip()
            if type_name in ("User*", "LocalUser*"):
                value = "user"
            elif type_name == "Channel*":
                value = "channel"
            elif type_name == "Membership*":
                value = "membership"
            elif type_name == "std::string":
                value = "command" if h["native"] == "OnPreCommand" else "text"
            else:
                value = {
                    "CUList": "exemptions",
                    "bool": "flag",
                    "char": "snomask",
                    "time_t": "timestamp",
                    "ModeHandler::Rank": "rank",
                    "MessageTarget": "message_target",
                    "MessageDetails": "details",
                    "User::NeighborList": "neighbors",
                    "User::NeighborExceptions": "exceptions",
                    "Modes::ChangeList": "modes",
                    "Modes::Change": "change",
                    "ModeParser::ModeProcessFlag": "processflags",
                    "Extensible*": "user",
                    "ExtensionType": "extype",
                    "XLine*": "&line",
                    "Module*": "target",
                    "CommandBase::Params": "parameters",
                    "Command*": "ping",
                    "CmdResult": "CmdResult::SUCCESS",
                    "int": "descriptor",
                    "ListenSocket*": "listener",
                    "irc::sockets::sockaddrs": "address",
                    "Numeric::Numeric": "numeric",
                    "ServiceProvider": "*this",
                    "ClientProtocol::Message": "message",
                    "std::shared_ptr<OperAccount>": "oper",
                    "std::shared_ptr<ConnectClass>": "klass",
                    "std::optional<Numeric::Numeric>": "errnum",
                }[type_name]
            if h["native"] == "OnUserPreJoin" and name == "chan":
                value = "nullptr"
            if h["native"] == "OnMode" and name == "usertarget":
                value = "nullptr"
            if h["native"] == "OnPreMode" and name == "dest":
                value = "nullptr"
            if h["native"] == "OnPreRehash" and name == "user":
                value = "nullptr"
            args.append(value)
        call = f"target->{h['native']}({', '.join(args)})"
        probe += f'\t\tif (selected == "*" || selected == "{h["js"]}")\n\t\t{{\n'
        probe += (
            f'\t\t\tRecord("{h["js"]}", {call});\n'
            if h["result"] == "ModResult"
            else f"\t\t\t{call};\n"
        )
        probe += "\t\t}\n"
    return {
        "tests/fixtures/module_hook_calls.inc": probe,
        "modules/js_generated/hook_specs.h": specs + "};\n",
        "modules/js_generated/hook_adapters.inc": adapters,
        "modules/js_generated/module_hooks.d.ts": types + "}\n",
        "bindings/module_hooks_coverage.md": coverage,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--upstream", type=pathlib.Path)
    args = parser.parse_args()
    try:
        hooks = validate(json.loads(MANIFEST.read_text()))
        if args.upstream:
            upstream_check(hooks, args.upstream)
        for name, content in outputs(hooks).items():
            path = ROOT / name
            if args.check:
                if not path.exists() or path.read_text() != content:
                    raise ValueError(f"generated drift: {name}")
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content)
    except (ValueError, KeyError) as error:
        print(error, file=sys.stderr)
        return 1
    print(
        f"PASS: {len(hooks)} Module hooks; generated adapters/schema/coverage"
        + (" and pinned upstream declarations" if args.upstream else "")
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
