#!/usr/bin/env python3
"""Generate MkDocs reference from reviewed module docs and declarations."""

import argparse
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    source = (ROOT / "JAVASCRIPT.md").read_text()
    sections = {}
    for block in source.split(chr(10) + "## ")[1:]:
        title, _, body = block.partition(chr(10))
        sections[title] = body
    mapping = {
        "configuration": ("Configuration", "Build and configure"),
        "commands": ("Command hooks", "Hooks and owned data"),
        "api": ("Native API and authority", "Native API and authority"),
        "limits": ("Execution and failure limits", "Failure and execution limits"),
        "hooks": ("Core Module hooks", "All core Module event hooks (InspIRCd 4.12.1)"),
        "events": (
            "Separate event-provider hooks",
            "Separate event-provider hooks (InspIRCd 4.12.1)",
        ),
    }
    outputs = {}
    for slug, (title, section) in mapping.items():
        body = sections[section].strip()
        body = re.sub(r"\]\(site-docs/([^)]*)\)", r"](../\1)", body)
        if slug == "hooks":
            body = body.replace(
                "[the per-hook inventory](bindings/module_hooks_coverage.md)",
                "[the per-hook inventory](#hook-inventory)",
            )
            inventory = (ROOT / "bindings/module_hooks_coverage.md").read_text()
            body += "\n\n## Hook inventory\n\n" + inventory.split("\n", 1)[1].strip()
            body += "\n\n## Complete TypeScript hook declarations\n\n~~~typescript\n"
            body += (ROOT / "modules/js_hooks.d.ts").read_text()
            body += (ROOT / "modules/js_generated/module_hooks.d.ts").read_text() + "\n~~~"
        if slug == "events":
            body += "\n\n## Complete TypeScript event declarations\n\n~~~typescript\n"
            body += (ROOT / "modules/js_events.d.ts").read_text() + "\n~~~"
        outputs["site-docs/reference/" + slug + ".md"] = (
            "<!-- Generated by tools/generate_docs_reference.py; edit JAVASCRIPT.md or the binding sources. -->\n"
            + "# "
            + title
            + "\n\n"
            + body
            + "\n"
        )
    outputs["site-docs/assets/js_fetch.d.ts"] = (ROOT / "modules/js_fetch.d.ts").read_text()
    outputs["site-docs/assets/js_api.d.ts"] = (ROOT / "modules/js_api.d.ts").read_text()
    outputs["site-docs/assets/js_events.d.ts"] = (ROOT / "modules/js_events.d.ts").read_text()
    outputs["site-docs/assets/js_hooks.d.ts"] = (ROOT / "modules/js_hooks.d.ts").read_text()
    outputs["site-docs/assets/js_generated/module_hooks.d.ts"] = (
        ROOT / "modules/js_generated/module_hooks.d.ts"
    ).read_text()
    outputs["site-docs/assets/js_generated/inspircd.d.ts"] = (
        ROOT / "modules/js_generated/inspircd.d.ts"
    ).read_text()
    outputs["site-docs/reference/api.md"] += (
        "\n## TypeScript assets\n\n[API declarations](../assets/js_api.d.ts), [snapshot types](../assets/js_hooks.d.ts), [hook declarations](../assets/js_generated/module_hooks.d.ts), [utility declarations](../assets/js_generated/inspircd.d.ts). Preserve this directory layout for triple-slash references.\n"
    )
    declarations = {
        "Host methods and data types": "modules/js_api.d.ts",
        "Asynchronous fetch jobs": "modules/js_fetch.d.ts",
        "Generated native utilities": "modules/js_generated/inspircd.d.ts",
    }
    method_names = set()
    parts = [
        "<!-- Generated by tools/generate_docs_reference.py; edit the declaration sources. -->",
        "# Callable JavaScript API",
        "These declarations describe this checkout, not every deployed server. "
        "See [authority and lifecycle](../explanation/host-lifecycle.md) before enabling admin scripts. "
        "Event callbacks are documented separately in [core hooks](hooks.md) and [event providers](events.md).",
    ]
    for title, filename in declarations.items():
        text = (ROOT / filename).read_text()
        method_names.update(re.findall(r"^  ([A-Za-z][A-Za-z0-9]*)\(", text, re.M))
        parts.extend(
            ["## " + title, "Source: `" + filename + "`.", "~~~typescript", text.rstrip(), "~~~"]
        )
    parts.insert(
        3, "## Method index\n\n" + ", ".join("`" + name + "`" for name in sorted(method_names))
    )
    outputs["site-docs/reference/callable-api.md"] = "\n\n".join(parts) + "\n"
    changed = []
    for name, text in outputs.items():
        path = ROOT / name
        if not path.exists() or path.read_text() != text:
            changed.append(name)
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text)
    if args.check and changed:
        raise SystemExit("Out of date: " + ", ".join(changed))
    print(
        "PASS: documentation reference matches reviewed sources"
        if args.check
        else "Generated documentation reference and type assets"
    )


if __name__ == "__main__":
    main()
