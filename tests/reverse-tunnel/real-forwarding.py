"""Real module, companion, SSH client/server and encrypted loopback forwarding.

Run only in the disposable Dockerfile.real image with --network none. Private
fixture keys are generated by ssh-keygen and opened only by OpenSSH; Python
reads public .pub files, never private keys. Nothing is mounted from the host.
"""
import fcntl
import os
from pathlib import Path
import pwd
import signal
import socket
import socketserver
import struct
import subprocess
import tempfile
import threading
import time

# Docker Desktop may expose dormant kernel tunnel devices even with network none.
# Check interface flags, not just device names: only loopback may be UP.
with socket.socket(socket.AF_INET, socket.SOCK_DGRAM) as probe:
    active = []
    for _, name in socket.if_nameindex():
        flags = fcntl.ioctl(probe, 0x8913, struct.pack('256s', name.encode()))
        if struct.unpack_from('H', flags, 16)[0] & 1:
            active.append(name)
    assert active == ['lo'], f'requires isolated loopback-only networking: {active}'
ROOT = Path(tempfile.mkdtemp(prefix='rt-real-', dir='/tmp'))
ROOT.chmod(0o755)
DAEMON_UID = 10000
DAEMON_GID = 10000
SSHD_PORT, IRC_PORT, TARGET_PORT = 2222, 16669, 16666
FORWARD_PORT, BAD_PORT = 16675, 16676


def eventually(fn, label, timeout=30):
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        if fn():
            return
        time.sleep(.1)
    raise AssertionError('timed out: ' + label)


def listening(port):
    try:
        with socket.create_connection(('127.0.0.1', port), timeout=.3):
            return True
    except OSError:
        return False


def processes(prefix):
    result = set()
    for item in Path('/proc').iterdir():
        if item.name.isdigit():
            try:
                # /proc metadata only, never process environments or credentials.
                name = (item / 'comm').read_text().strip()
                if name == prefix or name.startswith(prefix + '-'):
                    result.add(int(item.name))
            except (FileNotFoundError, ProcessLookupError):
                pass
    return result


class IRC:
    def __init__(self):
        self.sock = socket.create_connection(('127.0.0.1', IRC_PORT))
        self.sock.settimeout(.2)
        self.command('NICK realtest\r\nUSER test 0 * :test', ' 001 ')
        self.command('OPER admin testpass', ' 381 ')

    def command(self, command, expected):
        self.sock.sendall((command + '\r\n').encode())
        result = ''
        deadline = time.monotonic() + 20
        while time.monotonic() < deadline:
            try:
                data = self.sock.recv(65536)
                assert data, result
                result += data.decode()
            except socket.timeout:
                continue
            if expected in result:
                return result
        raise AssertionError(f'missing {expected!r}: {result!r}')


class Echo(socketserver.BaseRequestHandler):
    def handle(self):
        self.request.settimeout(2)
        try:
            data = self.request.recv(256)
            if data:
                self.request.sendall(b'encrypted-roundtrip:' + data)
        except OSError:
            pass


class EchoServer(socketserver.ThreadingTCPServer):
    allow_reuse_address = True
    daemon_threads = True


def forwarded():
    try:
        # Fresh unpredictable payload proves bidirectional data, not just bind.
        payload = os.urandom(32)
        expected = b'encrypted-roundtrip:' + payload
        with socket.create_connection(('127.0.0.1', FORWARD_PORT), timeout=.5) as conn:
            conn.settimeout(.5)
            conn.sendall(payload)
            received = b''
            while len(received) < len(expected):
                part = conn.recv(256)
                if not part:
                    return False
                received += part
            return received == expected
    except OSError:
        return False


def key(name, uid=0, gid=0):
    path = ROOT / name
    subprocess.run(['ssh-keygen', '-q', '-t', 'ed25519', '-N', '', '-f', str(path)], check=True)
    os.chown(path, uid, gid)
    return path


hostkey = key('host')
wrongkey = key('wrong-host')
identity = key('identity', DAEMON_UID, DAEMON_GID)
account = pwd.getpwnam('tunneltest')
authorized = Path(account.pw_dir) / '.ssh'
authorized.mkdir(mode=0o700)
os.chown(authorized, account.pw_uid, account.pw_gid)
authfile = authorized / 'authorized_keys'
authfile.write_text(Path(str(identity) + '.pub').read_text())
authfile.chmod(0o600)
os.chown(authfile, account.pw_uid, account.pw_gid)
for name, source in [('known-hosts', hostkey), ('wrong-known-hosts', wrongkey)]:
    public = Path(str(source) + '.pub').read_text().split()
    (ROOT / name).write_text(f'[127.0.0.1]:{SSHD_PORT} {public[0]} {public[1]}\n')

sshdconfig = ROOT / 'sshd.conf'
sshdconfig.write_text(f'''ListenAddress 127.0.0.1
Port {SSHD_PORT}
HostKey {hostkey}
PidFile {ROOT}/sshd.pid
AuthorizedKeysFile .ssh/authorized_keys
StrictModes yes
PasswordAuthentication no
KbdInteractiveAuthentication no
AuthenticationMethods publickey
PermitRootLogin no
AllowUsers tunneltest
AllowTcpForwarding remote
GatewayPorts no
PermitListen 127.0.0.1:{FORWARD_PORT} 127.0.0.1:{BAD_PORT}
PermitTTY no
X11Forwarding no
AllowAgentForwarding no
LogLevel VERBOSE
''')
subprocess.run(['/usr/sbin/sshd', '-t', '-f', str(sshdconfig)], check=True)
sshdlog = open(ROOT / 'sshd.log', 'w')
daemonlog = open(ROOT / 'daemon.log', 'w')
sshd = None
daemon = None
backend = EchoServer(('127.0.0.1', TARGET_PORT), Echo)
threading.Thread(target=backend.serve_forever, daemon=True).start()


def start_sshd():
    process = subprocess.Popen(['/usr/sbin/sshd', '-D', '-e', '-f', str(sshdconfig)], stdout=sshdlog, stderr=sshdlog)
    eventually(lambda: process.poll() is None and listening(SSHD_PORT), 'sshd listener')
    return process


def stop_sshd():
    # Every sshd here belongs to this disposable, network-isolated fixture.
    for pid in processes('sshd'):
        try:
            os.kill(pid, signal.SIGTERM)
        except ProcessLookupError:
            pass
    if sshd:
        sshd.wait(timeout=5)


try:
    sshd = start_sshd()
    base = f'''<server name="test.example" description="test" network="test" id="001">
<admin name="test" email="test@example.invalid" description="test">
<bind address="127.0.0.1" port="{IRC_PORT}" type="clients">
<connect allow="*" timeout="20" useident="no" resolvehostnames="no" fakelag="no">
<path moduledir="/inspircd/modules">
<power diepass="unused" restartpass="unused">
<module name="reverse_tunnel">
<class name="admin" commands="*" privs="servers/reverse-tunnel">
<type name="admin" classes="admin">
<oper name="admin" password="testpass" host="*@127.0.0.1" type="admin">
'''
    for name, known in [('edge', 'known-hosts'), ('bad', 'wrong-known-hosts')]:
        base += f'''<tunnelprofile name="{name}" host="127.0.0.1" port="{SSHD_PORT}" user="tunneltest"
 identityfile="{identity}" knownhostsfile="{ROOT}/{known}" destination="127.0.0.1"
 listenmin="{FORWARD_PORT}" listenmax="{BAD_PORT}" destmin="{TARGET_PORT}" destmax="{TARGET_PORT}">
'''
    config = ROOT / 'inspircd.conf'
    config.write_text(base + f'<reversetunnel name="real" profile="edge" listenport="{FORWARD_PORT}" destinationport="{TARGET_PORT}">\n')
    daemon = subprocess.Popen(['/inspircd/bin/inspircd', '--nofork', '--config', str(config)],
                              cwd='/inspircd', stdout=daemonlog, stderr=daemonlog,
                              user=DAEMON_UID, group=DAEMON_GID, extra_groups=[])
    eventually(lambda: daemon.poll() is None and listening(IRC_PORT), 'isolated IRC listener')
    irc = IRC()
    eventually(forwarded, 'real encrypted reverse forwarding')
    original_clients = processes('ssh')
    assert original_clients, 'real OpenSSH client did not run'
    # Inspect the kernel listener: requested gateway socket must be loopback-only.
    tcp = Path('/proc/net/tcp').read_text().splitlines()[1:]
    listeners = [line.split()[1] for line in tcp if line.split()[3] == '0A' and int(line.split()[1].split(':')[1], 16) == FORWARD_PORT]
    assert listeners == [f'0100007F:{FORWARD_PORT:04X}'], listeners
    print('PASS real OpenSSH encrypted bidirectional forwarding; remote listener is IPv4 loopback only')

    # A wrong pinned key must never reach public-key authentication or bind.
    before = (ROOT / 'sshd.log').read_text().count('Accepted publickey')
    irc.command(f'RTUNNEL ADD rejected bad {BAD_PORT} {TARGET_PORT}', 'change accepted')
    deadline = time.monotonic() + 12
    while time.monotonic() < deadline:
        assert not listening(BAD_PORT), 'wrong host key unexpectedly opened a forward'
        time.sleep(.25)
    status = irc.command('RTUNNEL SHOW rejected', 'owner=dynamic')
    assert 'state=backoff' in status, 'wrong host key did not produce failed-connection backoff'
    assert (ROOT / 'sshd.log').read_text().count('Accepted publickey') == before
    assert forwarded(), 'wrong-key attempt disrupted the valid tunnel'
    irc.command('RTUNNEL DELETE rejected', 'change accepted')
    print('PASS strict wrong-host-key rejection: retries observed, no authentication or remote listener')

    stop_sshd()
    eventually(lambda: not listening(FORWARD_PORT), 'remote listener closed after SSH server disconnect')
    eventually(lambda: not (processes('ssh') & original_clients), 'original client exited after disconnect')
    sshd = start_sshd()
    eventually(forwarded, 'encrypted forward recovered after SSH server restart')
    assert processes('ssh').isdisjoint(original_clients), 'reconnect did not replace the SSH child'
    print('PASS real SSH disconnect/reconnect: new client and successful encrypted roundtrip')

    irc.command('UNLOADMODULE reverse_tunnel', 'successfully unloaded')
    eventually(lambda: not processes('ssh') and not listening(FORWARD_PORT), 'unload removes SSH client and forward')
    print('PASS module unload removes real SSH client and remote listener')
    irc.command('LOADMODULE reverse_tunnel', 'successfully loaded')
    eventually(forwarded, 'declarative forward restored after reload')
    daemon.kill()
    daemon.wait(timeout=5)
    eventually(lambda: not processes('ssh') and not listening(FORWARD_PORT), 'daemon crash cleans up SSH client and forward')
    print('PASS daemon crash removes real SSH client and remote listener')
except BaseException:
    # Only fixture diagnostics; no private-key files or environment dumps.
    print((ROOT / 'daemon.log').read_text()[-6000:])
    print((ROOT / 'sshd.log').read_text()[-6000:])
    raise
finally:
    if daemon and daemon.poll() is None:
        daemon.terminate()
        daemon.wait(timeout=10)
    stop_sshd()
    backend.shutdown()
    backend.server_close()
    sshdlog.close()
    daemonlog.close()
